# 年齡組大約是哪幾年出生的（調查期間的頭尾減年齡的頭尾）
SURVEY_YEARS = {"2017-2020": (2017, 2020), "2013-2016": (2013, 2016)}


def birth_years(period: str, group: str) -> tuple[int, int]:
    first, last = SURVEY_YEARS[period]
    low, high = (int(x) for x in group.split("-"))
    return first - high, last - low
