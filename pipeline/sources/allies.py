def _year(date: str | None) -> int | None:
    return int(date[:4]) if date else None


def allied(iso3: str, year: int) -> bool:
    """那一年的 12 月 31 日有沒有邦交"""
    for start, end in HISTORY.get(iso3, []):
        s, e = _year(start), _year(end)
        if (s is None or s <= year) and (e is None or e > year):
            return True
    return False


def former(iso3: str, year: int) -> bool:
    """那一年年底以前曾經有邦交、現在已經斷交（1949 年底仍有邦交的國家也算）"""
    if allied(iso3, year):
        return False
    return any(start is None or _year(start) <= year for start, _end in HISTORY.get(iso3, []))


def check(current_allies: set[str], last_year: int) -> None:
    """逐年的國家數跟年表一致，最後一年的邦交國跟外交部通訊錄裡的大使館一致"""
    for year, expected in CHECK_COUNTS.items():
        n = sum(allied(iso3, year) for iso3 in HISTORY)
        if n != expected:
            raise RuntimeError(f"{year} 年底的邦交國算出 {n} 國，應該是 {expected} 國，請檢查 allies.HISTORY")
    mine = {iso3 for iso3 in HISTORY if allied(iso3, last_year)}
    if mine != current_allies:
        raise RuntimeError(
            f"allies.HISTORY 的 {last_year} 年邦交國跟外交部駐外館處通訊錄的大使館不一致："
            f"多了 {sorted(mine - current_allies)}，少了 {sorted(current_allies - mine)}；有新的建交、斷交時請更新 HISTORY"
        )
