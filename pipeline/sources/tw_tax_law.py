"""台灣的法定稅率：營利事業所得稅、綜合所得稅最高稅率與起徵點、加值型營業稅。

都是法律規定或財政部依法公告的金額（事實），依據：
- 所得稅法（全國法規資料庫，https://law.moj.gov.tw/LawClass/LawHistory.aspx?pcode=G0340003 ）第 5 條的歷次條文：
  - 營利事業所得稅：課稅所得額超過 10 萬元的部分 25%（2009 年以前）；2009-05-27 修正為 20%、自 99 年度施行，
    但 2010-06-15 再修正為 17%、同樣自 99 年度（2010 年）施行；2018-02-07 修正為 20%、自 107 年度（2018 年）施行。
  - 綜合所得稅：2009 年以前 6%、13%、21%、30%、40% 五級；2009-05-27 修正為 5%、12%、20%、30%、40%，自 99 年度施行；
    2014-06-04 增加 45% 一級（綜合所得淨額超過 1,000 萬元），自 104 年度施行；2018-02-07 取消 45%，自 107 年度施行。
  - 級距、免稅額、標準扣除額、薪資所得特別扣除額每遇消費者物價指數累計上漲 3% 以上時調整，財政部每年度公告。
- 各年度實際適用的金額：
  - 1999–2009 年（88–98 年度）：財政部財政資訊中心《綜合所得稅申報核定統計專冊》各年度的說明頁
    （https://www.fia.gov.tw/WEB/fia/ias/isa098/ISA98.html 等），寫了稅率級距與累進差額、免稅額、標準扣除額、薪資所得特別扣除額。
  - 2010–2021 年（99–110 年度）：同一份專冊的表 6-2「綜稅所得應納稅額及稅率各級距申報統計表」依稅率級距分列（萬元），
    說明頁有標準扣除額；臺北國稅局「適用稅率」頁（https://www.ntbt.gov.tw/multiplehtml/1b82b380e1a34de9afd204d39b007db2 ）
    列出 105 年度起的速算公式。
  - 2022–2026 年（111–115 年度）：財政部賦稅署每年度的公告與附表（https://www.dot.gov.tw/multiplehtml/ch26 ）。
  - 2010–2021 年的免稅額、2010–2014 年的薪資所得特別扣除額沒有找到官方的逐年附表（賦稅署網站只留 111 年度起的公告，
    專冊的說明頁 99 年度起不再寫這兩項），用最接近的、有官方數字的年份（`ASSUMED`）：實際的金額可能因物價調整多幾千元，
    換算成「平均薪資的幾倍」只差不到 0.1%。
- 加值型及非加值型營業稅法第 10 條：營業稅稅率最低 5%、最高 10%，由行政院定之；1986 年 4 月 1 日實施加值型營業稅起
  一直是 5%。

財政部財政資訊中心、賦稅署、臺北國稅局網站的「政府網站資料開放宣告」都採政府資料開放授權條款第 1 版；
法律條文與機關的公告不受著作權保護（著作權法第 9 條）。
"""
from __future__ import annotations

# 營利事業所得稅的法定稅率（%），{起始年: 稅率}；2000 年是資料的第一年（2009 年 5 月修正前的條文是 25%）
CIT = {2000: 25.0, 2010: 17.0, 2018: 20.0}

VAT = 5.0  # 加值型營業稅，1986-04-01 起
VAT_SINCE = 1986

# 各年度綜合所得稅的級距：(各級的上限（綜合所得淨額，新臺幣元；最後一級沒有上限）, 各級的稅率 %)
BRACKETS: dict[int, tuple[tuple[int, ...], tuple[int, ...]]] = {}
for _years, _bounds, _rates in (
    (range(1999, 2008), (370_000, 990_000, 1_980_000, 3_720_000), (6, 13, 21, 30, 40)),  # 88–96 年度（專冊）
    (range(2008, 2010), (410_000, 1_090_000, 2_180_000, 4_090_000), (6, 13, 21, 30, 40)),  # 97–98 年度（專冊）
    (range(2010, 2013), (500_000, 1_130_000, 2_260_000, 4_230_000), (5, 12, 20, 30, 40)),  # 99–101 年度（表 6-2）
    (range(2013, 2015), (520_000, 1_170_000, 2_350_000, 4_400_000), (5, 12, 20, 30, 40)),  # 102–103 年度（表 6-2）
    (range(2015, 2017), (520_000, 1_170_000, 2_350_000, 4_400_000, 10_000_000), (5, 12, 20, 30, 40, 45)),  # 104–105
    ([2017], (540_000, 1_210_000, 2_420_000, 4_530_000, 10_310_000), (5, 12, 20, 30, 40, 45)),  # 106 年度
    (range(2018, 2022), (540_000, 1_210_000, 2_420_000, 4_530_000), (5, 12, 20, 30, 40)),  # 107–110 年度
    (range(2022, 2024), (560_000, 1_260_000, 2_520_000, 4_720_000), (5, 12, 20, 30, 40)),  # 111–112 年度（公告）
    (range(2024, 2026), (590_000, 1_330_000, 2_660_000, 4_980_000), (5, 12, 20, 30, 40)),  # 113–114 年度（公告）
    ([2026], (610_000, 1_380_000, 2_770_000, 5_190_000), (5, 12, 20, 30, 40)),  # 115 年度（公告）
):
    for _y in _years:
        BRACKETS[_y] = (_bounds, _rates)

# 各年度的綜合所得稅（新臺幣元）：最高稅率、最高一級的起點（綜合所得淨額超過這個金額的部分）、
# 每人免稅額（未滿 70 歲）、單身的標準扣除額、薪資所得特別扣除額
PIT: dict[int, dict[str, float]] = {
    y: {"rate": rates[-1], "top_from": bounds[-1]} for y, (bounds, rates) in BRACKETS.items()
}


def _set(years: range | list[int], **values: float) -> None:
    for y in years:
        PIT.setdefault(y, {}).update(values)


# 免稅額、標準扣除額、薪資所得特別扣除額
_set([1999], exemption=72_000, standard=43_000, salary=60_000)
_set([2000], exemption=72_000, standard=44_000, salary=75_000)
_set(range(2001, 2006), exemption=74_000, standard=44_000, salary=75_000)
_set([2006], exemption=77_000, standard=46_000, salary=78_000)
_set([2007], exemption=77_000, standard=46_000, salary=78_000)
_set([2008], exemption=77_000, standard=73_000, salary=100_000)
_set([2009], exemption=82_000, standard=76_000, salary=104_000)
_set(range(2010, 2013), standard=76_000)
_set(range(2013, 2015), standard=79_000)
_set(range(2015, 2018), standard=90_000, salary=128_000)  # 薪資所得特別扣除額 12.8 萬元是 2014 年修正的第 17 條
_set(range(2018, 2022), standard=120_000, salary=200_000)  # 2018 年修正的第 17 條：標準扣除額 12 萬、薪資 20 萬
_set(range(2018, 2022), exemption=88_000)  # 111 年度公告：免稅額「由 8.8 萬元提高至 9.2 萬元」
_set(range(2022, 2024), exemption=92_000, standard=124_000, salary=207_000)
_set(range(2024, 2026), exemption=97_000, standard=131_000, salary=218_000)
_set([2026], exemption=101_000, standard=136_000, salary=227_000)
# 沒有官方逐年數字的：用 2009 年（98 年度）專冊的金額
ASSUMED = {"exemption": range(2010, 2018), "salary": range(2010, 2015)}
for _key, _years in ASSUMED.items():
    _set(_years, **{_key: PIT[2009][_key]})

