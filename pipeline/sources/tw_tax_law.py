def cit_rate(year: int) -> float:
    return CIT[max(y for y in CIT if y <= year)]


def gross_threshold(year: int) -> float:
    """最高稅率開始適用的薪資收入（單身、只有薪資、用標準扣除額）：綜合所得淨額的起點加上免稅額與兩項扣除額。
    跟 OECD 的起徵點一樣是以薪資總額計（OECD 的表加回各國標準的免稅額與扣除額）。"""
    p = PIT[year]
    return p["top_from"] + p["exemption"] + p["standard"] + p["salary"]


def check() -> None:
    for year, p in PIT.items():
        missing = {"rate", "top_from", "exemption", "standard", "salary"} - set(p)
        if missing:
            raise RuntimeError(f"台灣 {year} 年的綜合所得稅參數缺 {missing}")
