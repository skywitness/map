def indicator(kind: str, iso3s: list[str]) -> tuple[dict[str, int], dict[str, tuple[str, str]], dict[str, str]]:
    """({iso3: 年齡或類別代碼}, {iso3: (中文附註, 英文附註)}, {iso3: 各地不同的範圍})，只留 iso3s 裡的國家。"""
