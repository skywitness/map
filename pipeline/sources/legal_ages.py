    values = {k: v for k, v in AGES[kind].items() if k in keep}
    notes: dict[str, tuple[str, str]] = {}
    for iso3, (zh, en) in NOTES[kind].items():
        if iso3 in values:
            notes[iso3] = (zh + "。", en + ".")
    varies = {k: v for k, v in VARIES[kind].items() if k in values}
    for iso3, span in varies.items():
        zh, en = notes.get(iso3, ("", ""))
