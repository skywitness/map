def parse(text: str) -> list[tuple[float, float]]:
    out = []
    for pair in text.split(" - "):
        lat, lon = pair.split()
        la, lo = lat[:-1], lon[:-1]
        out.append((dms(int(la[:2]), int(la[2:4]), int(la[4:6] or 0)), dms(int(lo[:3]), int(lo[3:5]), int(lo[5:7] or 0))))
    return out
