const MAX = 4;

/** 這個主題的相關主題：自己寫的在前，再補上連到它的（反方向），最多 MAX 個 */
export function relatedTopics(id: string): string[] {
  const own = RELATED[id] ?? [];
  const back = Object.keys(RELATED).filter((other) => other !== id && RELATED[other].includes(id) && !own.includes(other));
  return [...own, ...back].slice(0, MAX);
}
